"""
تسلسل عمليات التعديل (قراءة ← تعديل ← حفظ) على محتوى المعلم والتقييمات.

كل تعديل يقرأ القائمة كاملة ثم يعيد كتابتها، فلو نفّذ معلمان تعديلين في اللحظة
نفسها لضاع أحدهما (آخر حفظ يفوز). هذا القفل يجعل التعديلات تُنفَّذ واحدًا
بعد الآخر داخل عملية الخادم الواحدة (نسخة Render الواحدة). لا يغطي أكثر من
نسخة خادم تعمل معًا — لذلك يكفي هذا الحل ما دام الخادم نسخة واحدة.
"""
import threading

_lock = threading.Lock()


def serialize_writes():
    """dependency (بـ yield): تمسك القفل طوال تنفيذ الـendpoint ثم تفكّه."""
    with _lock:
        yield
