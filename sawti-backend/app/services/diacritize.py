def _dict_diacritize(text: str) -> str:
    words = text.split()
    result = []
    for word in words:
        clean = word.strip(".,،؟!؛:«»")
        suffix = word[len(clean):]
        result.append(COMMON.get(clean, clean) + suffix)
    output = " ".join(result)
    if output and output[-1] not in ".،؟!؛:":
        output += "."
    return output
