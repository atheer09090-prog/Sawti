def diacritize_text(text: str) -> str:
    if not text or not text.strip():
        return text

    api_key = os.getenv("GEMINI_API_KEY", "")
    if not api_key:
        return _dict_diacritize(text)

    try:
        url = (
            "https://generativelanguage.googleapis.com/v1beta/models/"
            f"gemini-2.0-flash:generateContent?key={api_key}"
        )
        prompt = """أنت خبير في النحو والصرف العربي. مهمتك إضافة التشكيل الكامل والدقيق لنص عربي.

القواعد الصارمة:
- ضع حركة على كل حرف بدون استثناء
- الأفعال الماضية: آخرها فتحة (ذَهَبَ، كَانَ، قُمْنَا)
- الأسماء المرفوعة: آخرها ضمة (الْبَحْرُ، رِحْلَةٌ)
- الأسماء المجرورة بعد حروف الجر: آخرها كسرة (فِي الْبَحْرِ، عَلَى الشَّاطِئِ)
- الأسماء المنصوبة: آخرها فتحة (رِحْلَةً جَمِيلَةً)
- التنوين على الاسم النكرة المنصوب: (جِدًّا، كَثِيرًا)
- حرف الواو العاطفة: (وَ)
- لا تضع سكوناً في نهاية الكلمة إلا إذا كانت مجزومة حقاً
- أعد النص فقط مع التشكيل، بدون أي كلام إضافي

النص:
""" + text

        payload = json.dumps({
            "contents": [{"parts": [{"text": prompt}]}],
            "generationConfig": {"temperature": 0.0, "maxOutputTokens": 1024},
        }).encode("utf-8")

        req = urllib.request.Request(
            url, data=payload,
            headers={"Content-Type": "application/json"},
            method="POST",
        )
        with urllib.request.urlopen(req, timeout=15) as resp:
            data = json.loads(resp.read())
            result = data["candidates"][0]["content"]["parts"][0]["text"].strip()
            return result if result else _dict_diacritize(text)
    except Exception:
        return _dict_diacritize(text)


def _dict_diacritize(text: str) -> str:
    words = text.split()
    result = []
    for word in words:
        clean = word.strip(".,،؟!؛:«»")
        suffix = word[len(clean):]
        result.append(COMMON.get(clean, clean) + suffix)
    output = " ".join(result)
    if output and output[-1] not in ".،؟!؛:":
        output += "."
    return output
