def diacritize_text(text: str) -> str:
    """
    يشكّل النص العربي كلمة كلمة من القاموس،
    ويضيف نقطة في النهاية إن لم تكن موجودة.
    """
    if not text:
        return text

    words = text.split()
    result = []

    for word in words:
        # نظّف الكلمة من علامات الترقيم للبحث
        clean = word.strip(".,،؟!؛:")
        # ابحث في القاموس
        diacritized = DIACRITICS_DICT.get(clean, DIACRITICS_DICT.get(word, word))
        # أعد علامات الترقيم إن كانت موجودة
        if word != clean:
            suffix = word[len(clean):]
            result.append(diacritized + suffix)
        else:
            result.append(diacritized)

    output = " ".join(result)

    # أضف نقطة في النهاية إن لم تكن هناك علامة ترقيم
    if output and output[-1] not in ".،؟!؛:":
        output += "."

    return output
